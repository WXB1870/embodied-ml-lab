// Mathematical checks for the interactive teaching examples (no browser emulation).
const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const path = require('node:path');
const context = vm.createContext({document:{addEventListener(){}},emlExplorer(){return '';},initExplorers(){}});
vm.runInContext(fs.readFileSync(path.join(__dirname,'../dist/p0-explorers.js'),'utf8'),context);
const math=vm.runInContext('P0Math',context);
let checks=0;
function near(actual,expected,message){assert.ok(Math.abs(actual-expected)<1e-9,`${message}: ${actual} vs ${expected}`);checks++;}
const p=math.softmax([1002,1001,999]);
const shifted=math.softmax([2,1,-1]);
p.forEach((v,i)=>near(v,shifted[i],'softmax shift invariance'));
near(p.reduce((a,b)=>a+b,0),1,'probability sum');
const input=Array.from({length:5},(_,r)=>Array.from({length:5},(_,c)=>r*5+c+1));
const kernel=Array.from({length:3},()=>[1,1,1]);
near(math.convolution(input,kernel)[0][0],63,'direct 3x3 sum');
near(math.convolution(input,kernel,2)[0][1],81,'stride 2');
near(math.convolution(input,kernel,1,0,2)[0][0],117,'dilated 3x3');
near(math.convolution([[1,2],[3,4]],kernel,1,1)[0][0],10,'zero padding');
near(math.gradient(.5).da,-.75,'chain rule');
near(math.gradient(.5,'freeze').da,-.75,'gradient through frozen factor');
assert.equal(math.gradient(.5,'freeze').dw,null);checks++;
assert.equal(math.gradient(.5,'detach').da,null);checks++;
near(math.accumulated(6,2,1).weighted,.5,'unequal micro-batch weighting');
near(math.accumulated(6,2,1).naive,-1,'mean of means counterexample');
near(math.accumulated(1,8,1).clipped,-1,'clip after accumulation');
const geo=math.geometry(240,60,'letterbox');
near(geo.x,168,'letterbox x');near(geo.y,91,'letterbox y');
assert.ok(math.geometry(0,60,'crop').x<0);checks++;
assert.equal(math.queue(250,10).first,3);checks++;
assert.equal(math.queue(300,10).first,3);checks++;
assert.equal(math.queue(900,10).available,0);checks++;
near(math.bellman(1,.9,4,false),4.6,'bootstrap on continuation or external truncation');
near(math.bellman(1,.9,4,true),1,'no bootstrap on termination');
const mlpContext=vm.createContext({document:{addEventListener(){}}});
vm.runInContext(fs.readFileSync(path.join(__dirname,'../dist/explorers.js'),'utf8'),mlpContext);
const params=vm.runInContext('mlpParameterCounts',mlpContext);
near(params(4).total,88,'four-class MLP H=4');
near(params(32).first,544,'MLP first layer H=32');
near(params(32).second,132,'MLP four-class output H=32');
near(params(32).total,676,'MLP total H=32');
near(params(128).total,2692,'four-class MLP H=128');
console.log(`${checks} mathematical visualization checks passed.`);
